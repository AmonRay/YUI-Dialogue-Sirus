#!/usr/bin/env python3
"""DialogueUI 3.3.5a (Sirus) texture conversion.

The 3.3.5a client cannot load PNG/JPG and draws nothing for textures whose size is not a power of two.
Every image under Art/ is converted to BLP2 with uncompressed BGRA pixels (encoding 3, 8-bit alpha,
no mipmaps - the same layout as the BLP files shipped by ElvUI-for-Sirus). Images whose size is not a
power of two are scaled up to the next power of two (texture coordinates are normalized, so every
SetTexCoord stays valid). The original pixel sizes are written to Code/Compat/TextureSizes_335.lua
(used by the 9-slice emulation in Compat_335.lua). A source file is removed only after its BLP has been
written and read back pixel-exact. Re-running is safe (already converted files are kept).

    python scripts/convert_textures_335.py          # convert Art/ and rewrite TextureSizes_335.lua
    python scripts/convert_textures_335.py --refs   # also strip image extensions from Lua/XML references
                                                    # ("X.tga" -> "X": the client then resolves X.blp)
"""
import os
import re
import struct
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ART = os.path.join(ROOT, 'Art')
SIZES_LUA = os.path.join(ROOT, 'Code', 'Compat', 'TextureSizes_335.lua')
SRC_EXT = ('.tga', '.jpg', '.jpeg', '.png', '.blp')
HEADER_SIZE = 1172
MAX_SIZE = 2048
SKIP_TOP = {'.git', '.github', '.idea', '.vscode', 'dist', '_Build', '_Dev', 'scripts', 'node_modules',
            'Art', 'Fonts', 'Sound'}
REF_RE = re.compile(r'\.(?:tga|jpe?g|png|blp)(?=["\':|])', re.I)


def next_pot(n):
    p = 1
    while p < n:
        p <<= 1
    return min(p, MAX_SIZE)


def read_header(path):
    with open(path, 'rb') as f:
        h = f.read(24)
    if len(h) < 24 or h[:4] != b'BLP2':
        return False, (0, 0)
    ours = struct.unpack('<I', h[4:8])[0] == 1 and h[8] == 3 and h[9] == 8 and h[11] == 0
    return ours, struct.unpack('<II', h[12:20])


def encode_blp(img):
    w, h = img.size
    r, g, b, a = img.split()
    data = Image.merge('RGBA', (b, g, r, a)).tobytes()   # BGRA byte order
    header = bytearray(HEADER_SIZE)
    header[0:4] = b'BLP2'
    struct.pack_into('<I', header, 4, 1)               # type 1: raw / DirectX
    header[8] = 3                                      # encoding 3: uncompressed BGRA
    header[9] = 8                                      # alpha depth
    header[10] = 8                                     # alpha encoding (as in ElvUI-for-Sirus)
    header[11] = 0                                     # no mipmaps
    struct.pack_into('<II', header, 12, w, h)
    struct.pack_into('<I', header, 20, HEADER_SIZE)    # mip 0 offset
    struct.pack_into('<I', header, 84, len(data))      # mip 0 size
    return bytes(header) + data


def decode_blp(raw):
    if raw[:4] != b'BLP2' or raw[8] != 3:
        raise ValueError('not an uncompressed BLP2')
    w, h = struct.unpack('<II', raw[12:20])
    off, = struct.unpack('<I', raw[20:24])
    size, = struct.unpack('<I', raw[84:88])
    if off != HEADER_SIZE or size != w * h * 4 or len(raw) != HEADER_SIZE + size:
        raise ValueError('bad BLP layout')
    b, g, r, a = Image.frombytes('RGBA', (w, h), raw[off:off + size]).split()
    return Image.merge('RGBA', (r, g, b, a))


def load_sizes():
    sizes = {}
    if os.path.exists(SIZES_LUA):
        with open(SIZES_LUA, 'r', encoding='utf-8') as f:
            for m in re.finditer(r'S\["([^"]+)"\]\s*=\s*\{(\d+),\s*(\d+)\}', f.read()):
                sizes[m.group(1)] = (int(m.group(2)), int(m.group(3)))
    return sizes


def write_sizes(sizes):
    lines = [
        '-- Generated by scripts/convert_textures_335.py - do not edit by hand.',
        '-- Original pixel size of every texture in Art/ (the BLP files are scaled to a power of two).',
        '-- Key: lower-case path relative to Art/, forward slashes, no extension.',
        'local _, addon = ...',
        'local S = {}',
        'addon.TextureFileSizes = S',
        '',
    ]
    for key in sorted(sizes):
        w, h = sizes[key]
        lines.append('S["%s"] = {%d, %d}' % (key, w, h))
    with open(SIZES_LUA, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


def convert():
    old_sizes = load_sizes()
    sizes, resized, failed = {}, [], []
    converted = kept = 0
    for dp, dn, fn in os.walk(ART):
        dn.sort()
        for f in sorted(fn):
            base, ext = os.path.splitext(f)
            if ext.lower() not in SRC_EXT:
                continue
            src = os.path.join(dp, f)
            dst = os.path.join(dp, base + '.blp')
            key = os.path.relpath(os.path.join(dp, base), ART).replace('\\', '/').lower()
            if key in sizes:
                failed.append('%s: several source images with this name' % key)
                continue
            if ext.lower() == '.blp':
                ours, (w, h) = read_header(src)
                if ours:
                    sizes[key] = old_sizes.get(key, (w, h))
                    kept += 1
                    continue
            try:
                img = Image.open(src)
                img.load()
            except Exception as e:  # keep the file, report it
                failed.append('%s: cannot decode (%s)' % (key, e))
                continue
            ow, oh = img.size
            img = img.convert('RGBA')
            tw, th = next_pot(ow), next_pot(oh)
            if (tw, th) != (ow, oh):
                img = img.convert('RGBa').resize((tw, th), Image.LANCZOS).convert('RGBA')
                resized.append('%s %dx%d -> %dx%d' % (key, ow, oh, tw, th))
            tmp = dst + '.tmp'
            with open(tmp, 'wb') as fh:
                fh.write(encode_blp(img))
            with open(tmp, 'rb') as fh:
                back = decode_blp(fh.read())
            if back.size != img.size or back.tobytes() != img.tobytes():
                os.remove(tmp)
                failed.append('%s: read-back mismatch' % key)
                continue
            if os.path.normcase(os.path.abspath(src)) != os.path.normcase(os.path.abspath(dst)):
                os.remove(src)
            os.replace(tmp, dst)
            sizes[key] = (ow, oh)
            converted += 1
    write_sizes(sizes)
    print('converted: %d, already BLP: %d, sizes written: %d' % (converted, kept, len(sizes)))
    for line in resized:
        print('  resized  ' + line)
    for line in failed:
        print('  FAILED   ' + line)
    return not failed


def strip_refs():
    total = 0
    for dp, dn, fn in os.walk(ROOT):
        top = os.path.relpath(dp, ROOT).split(os.sep)[0]
        if top in SKIP_TOP:
            dn[:] = []
            continue
        for f in fn:
            if not f.lower().endswith(('.lua', '.xml')):
                continue
            path = os.path.join(dp, f)
            with open(path, 'rb') as fh:
                text = fh.read().decode('utf-8')
            new, n = REF_RE.subn('', text)
            if n:
                with open(path, 'wb') as fh:
                    fh.write(new.encode('utf-8'))
                total += n
                print('  refs     %s: %d' % (os.path.relpath(path, ROOT), n))
    print('image extensions stripped: %d' % total)


if __name__ == '__main__':
    ok = convert()
    if '--refs' in sys.argv:
        strip_refs()
    sys.exit(0 if ok else 1)
